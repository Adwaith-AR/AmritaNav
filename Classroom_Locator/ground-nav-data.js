class GroundRouter {
  constructor(data) {
    this.nodes = data.nodes;
    this.edges = data.edges;
    this.rooms = data.rooms;
    this.scale = data.scaleMetersPerPixel || 0.15;
    this.walkingSpeed = data.avgWalkingSpeedMps || 1.25;

    this.roomsMap = new Map();
    this.rooms.forEach(r => this.roomsMap.set(r.id, r));

    this.adj = new Map();
    for (let i = 0; i < this.nodes.length; i++) {
      this.adj.set(i, new Map());
    }
    for (const e of this.edges) {
      this.adj.get(e.u).set(e.v, e.dist);
      this.adj.get(e.v).set(e.u, e.dist);
    }
  }

  dist(p1, p2) {
    const dx = p1[0] - p2[0];
    const dy = p1[1] - p2[1];
    return Math.sqrt(dx * dx + dy * dy);
  }

  pointToSegmentDist(p, a, b) {
    const abx = b[0] - a[0];
    const aby = b[1] - a[1];
    const abl2 = abx * abx + aby * aby;
    if (abl2 < 1e-6) {
      return { dist: this.dist(p, a), proj: a };
    }
    let t = ((p[0] - a[0]) * abx + (p[1] - a[1]) * aby) / abl2;
    t = Math.max(0, Math.min(1, t));
    const proj = [a[0] + t * abx, a[1] + t * aby];
    return { dist: this.dist(p, proj), proj };
  }

  findNearestCorridorPoint(x, y) {
    let bestDist = Infinity;
    let bestProj = [x, y];
    let nearestNode = 0;

    for (const edge of this.edges) {
      const uPt = this.nodes[edge.u];
      const vPt = this.nodes[edge.v];
      const res = this.pointToSegmentDist([x, y], uPt, vPt);
      if (res.dist < bestDist) {
        bestDist = res.dist;
        bestProj = res.proj;
      }
    }

    let minNodeDist = Infinity;
    for (let i = 0; i < this.nodes.length; i++) {
      const d = this.dist([x, y], this.nodes[i]);
      if (d < minNodeDist) {
        minNodeDist = d;
        nearestNode = i;
      }
    }

    return { proj: bestProj, dist: bestDist, nearestNode };
  }

  dijkstra(startNode, endNode) {
    if (startNode === endNode) {
      return { distance: 0, path: [startNode] };
    }

    const dist = new Array(this.nodes.length).fill(Infinity);
    const prev = new Array(this.nodes.length);
    const visited = new Uint8Array(this.nodes.length);

    dist[startNode] = 0;
    const pq = [{ node: startNode, d: 0 }];

    while (pq.length > 0) {
      let minIdx = 0;
      for (let i = 1; i < pq.length; i++) {
        if (pq[i].d < pq[minIdx].d) minIdx = i;
      }
      const { node: u, d: currentDist } = pq.splice(minIdx, 1)[0];

      if (visited[u]) continue;
      visited[u] = 1;
      if (u === endNode) break;

      const neighbors = this.adj.get(u);
      if (!neighbors) continue;

      for (const [v, weight] of neighbors.entries()) {
        if (visited[v]) continue;
        const alt = currentDist + weight;
        if (alt < dist[v]) {
          dist[v] = alt;
          prev[v] = u;
          pq.push({ node: v, d: alt });
        }
      }
    }

    if (dist[endNode] === Infinity) {
      return { distance: Infinity, path: [] };
    }

    const path = [];
    let curr = endNode;
    while (curr !== undefined) {
      path.unshift(curr);
      curr = prev[curr];
    }

    return { distance: dist[endNode], path };
  }

  resolveTarget(target) {
    if (typeof target === 'string') {
      const room = this.roomsMap.get(target);
      if (room) {
        return {
          id: room.id,
          name: room.name,
          code: room.code,
          x: room.cx,
          y: room.cy,
          entryX: room.entryX,
          entryY: room.entryY,
          node: room.node,
          isRoom: true
        };
      }
    } else if (target && typeof target === 'object') {
      const x = target.x;
      const y = target.y;
      const nearest = this.findNearestCorridorPoint(x, y);
      return {
        id: 'gps_location',
        name: target.name || 'Current Location',
        code: 'GPS',
        x,
        y,
        entryX: nearest.proj[0],
        entryY: nearest.proj[1],
        node: nearest.nearestNode,
        isRoom: false
      };
    }
    return null;
  }

  findRoute(originTarget, destTarget) {
    const origin = this.resolveTarget(originTarget);
    const dest = this.resolveTarget(destTarget);

    if (!origin || !dest) return { success: false, error: 'Invalid start or destination location' };

    if (origin.id === dest.id) {
      return {
        success: true,
        points: [[origin.x, origin.y]],
        totalDistanceMeters: 0,
        timeFormatted: '0 min',
        origin,
        dest
      };
    }

    const { distance: corridorDist, path: nodePath } = this.dijkstra(origin.node, dest.node);
    if (corridorDist === Infinity || nodePath.length === 0) {
      return { success: false, error: 'No walkable corridor path found' };
    }

    const points = [];
    points.push([origin.x, origin.y]);
    if (origin.entryX !== origin.x || origin.entryY !== origin.y) {
      points.push([origin.entryX, origin.entryY]);
    }

    for (const nodeIdx of nodePath) {
      const pt = this.nodes[nodeIdx];
      const last = points[points.length - 1];
      if (this.dist(last, pt) > 1.0) {
        points.push(pt);
      }
    }

    if (dest.entryX !== dest.x || dest.entryY !== dest.y) {
      points.push([dest.entryX, dest.entryY]);
    }
    points.push([dest.x, dest.y]);

    let totalDistPx = 0;
    for (let i = 0; i < points.length - 1; i++) {
      totalDistPx += this.dist(points[i], points[i + 1]);
    }

    const totalDistanceMeters = Math.round(totalDistPx * this.scale);
    const timeSec = Math.round(totalDistanceMeters / this.walkingSpeed);
    const minutes = Math.floor(timeSec / 60);
    const seconds = timeSec % 60;
    const timeFormatted = minutes > 0 ? (minutes + ' min' + (seconds > 0 ? ' ' + seconds + 's' : '')) : (seconds + ' sec');

    return {
      success: true,
      points,
      totalDistanceMeters,
      timeFormatted,
      origin,
      dest
    };
  }
}

window.GroundRouter = GroundRouter;

